-- School Event Registration System: Supabase setup
-- Run the ENTIRE script in Supabase Dashboard > SQL Editor > New query.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text,
  role text not null default 'student' check (role in ('student','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  event_date date not null,
  event_time time not null,
  location text not null,
  capacity integer not null default 100 check (capacity > 0),
  created_at timestamptz not null default now()
);
create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  event_id bigint not null references public.events(id) on delete cascade,
  registered_at timestamptz not null default now(),
  unique(user_id,event_id)
);
create index if not exists registrations_event_id_idx on public.registrations(event_id);
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,full_name,email,role)
  values(new.id, coalesce(new.raw_user_meta_data->>'full_name','Student'), new.email, 'student')
  on conflict (id) do nothing;
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role='admin');
$$;

alter table public.profiles enable row level security;
alter table public.events enable row level security;
alter table public.registrations enable row level security;
create policy "Profiles readable by self or admin" on public.profiles for select to authenticated
using (id=auth.uid() or public.is_admin());
create policy "Events visible to everyone" on public.events for select to anon, authenticated using (true);
create policy "Admins create events" on public.events for insert to authenticated with check (public.is_admin());
create policy "Admins update events" on public.events for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Admins delete events" on public.events for delete to authenticated using (public.is_admin());
create policy "Registrations visible to owner or admin" on public.registrations for select to authenticated
using (user_id=auth.uid() or public.is_admin());
create policy "Users cancel own registrations or admin" on public.registrations for delete to authenticated
using (user_id=auth.uid() or public.is_admin());

-- Secure capacity check + duplicate prevention in one database transaction.
create or replace function public.register_for_event(p_event_id bigint)
returns void language plpgsql security definer set search_path=public as $$
declare event_capacity integer; current_count integer;
begin
  if auth.uid() is null then raise exception 'Please log in first.'; end if;
  select capacity into event_capacity from public.events where id=p_event_id for update;
  if event_capacity is null then raise exception 'Event not found.'; end if;
  select count(*) into current_count from public.registrations where event_id=p_event_id;
  if current_count >= event_capacity then raise exception 'This event is already full.'; end if;
  insert into public.registrations(user_id,event_id) values(auth.uid(),p_event_id);
end; $$;
revoke all on function public.register_for_event(bigint) from public;
grant execute on function public.register_for_event(bigint) to authenticated;

