-- Public event capacity display without exposing students' personal registrations.
create or replace function public.get_event_registration_counts()
returns table(event_id bigint, registered_count bigint)
language sql stable security definer set search_path=public as $$
  select e.id, count(r.id)::bigint
  from public.events e left join public.registrations r on r.event_id=e.id
  group by e.id;
$$;
revoke all on function public.get_event_registration_counts() from public;
grant execute on function public.get_event_registration_counts() to anon, authenticated;
